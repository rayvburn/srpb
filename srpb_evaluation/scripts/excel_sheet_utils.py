from openpyxl import load_workbook
from openpyxl import Workbook
from pathlib import Path
from typing import Dict
from typing import List

# name of the sheet in the Excel file with the results
SHEET_NAME = "SRPB"

# upper left cell - cell that initiates results table
RESULT_RAW_INIT_COL = 'A'
RESULT_RAW_INIT_ROW = '1'
# filtered (mean/median)
RESULT_INIT_COL = 'A'
RESULT_INIT_ROW = '50'


def increment_column(col: str):
    """
    Increments the ID of the column using A-Z characters, e.g., passing Z gives AA
    :param col column ID to be incremented
    """
    if col == None:
        raise Exception("Could not increment 'None'")

    # lambda that works for chars in A-Z range
    increment_char = lambda c : chr(ord(c) + 1)

    # Generated by ChatGPT
    if col == "":
        return "A"
    if col[-1] != 'Z':
        return col[:-1] + increment_char(col[-1])
    else:
        i = len(col) - 1
        while i >= 0 and col[i] == 'Z':
            i -= 1
        if i == -1:
            return 'A' * (len(col) + 1)
        else:
            return col[:i] + increment_char(col[i]) + 'A' * (len(col) - i - 1)


def read_data_from_excel(wb: Workbook, sheet_name: str, col_init: str, row_init: int) -> Dict[str, Dict[str, float]]:
    """
    Reads the spreadsheet following the convention introduced in `create_excel_from_results.calculate_sheet` script
    :param wb loaded workbook of the spreadsheet
    :param sheet_name specific sheet to access
    :param col_init column of the upper left cell - cell that initiates results table
    :param row_init row of the upper left cell - cell that initiates results table
    """

    sheet = wb[sheet_name]
    col_metric_ids = col_init

    # lambda that creates col-row tuple to access cell in a sheet
    make_sheet_cell = lambda row, col : str(col + row)
    # lambda that increments integer stored as string
    increment_row = lambda row : str(int(row) + 1)
    # lambda that retrieves value of sheet's cell
    get_sheet_val = lambda sheet, row, col : sheet[make_sheet_cell(col=col, row=row)].value
    # lambda that checks if certain cell in the sheet is empty
    sheet_cell_empty = lambda sheet, row, col : get_sheet_val(sheet=sheet, row=row, col=col) == None

    # local database with planners' metrics, actually:
    # Dict[str, Dict[str, List[float]]]
    # str: planner ID
    #   str: metric ID
    #     list[float]: metric values for the subsequent trials
    data = {}

    # to iterate over planners - skip first, avoiding 'Planner'
    col_iter = increment_column(col_init)
    # to iterate over metrics
    row_iter = increment_row(row_init)
    # iterate over planners (names)
    while not sheet_cell_empty(sheet=sheet, row=row_init, col=col_iter):
        # save planner name for later use in database
        planner_name = str(get_sheet_val(sheet=sheet, row=row_init, col=col_iter))
        # print(f"Checking sheet at {make_sheet_cell(col=col_iter, row=row_init)} for planner {planner_name}")
        # got a valid planner name - iterate over saved metrics
        metric_names = []
        metric_values = []
        while not sheet_cell_empty(sheet=sheet, row=row_iter, col=col_metric_ids):
            # obtain sheet values
            metric_name = get_sheet_val(sheet=sheet, row=row_iter, col=col_metric_ids)
            metric_value = get_sheet_val(sheet=sheet, row=row_iter, col=col_iter)
            # evaluate the correctness of read data
            if metric_name == None or metric_value == None:
                raise Exception(
                    f"The metric ID cell `{col_metric_ids}{row_iter}` contains `{metric_name}` "
                    f"and the metric value cell `{col_iter}{row_iter}` contains `{metric_value}`. "
                    f"Cannot proceed with such values. Check whether the cells in your spreadsheet are empty. "
                    f"If they aren't, try to open the sheet and simply save it using Excel or LibreOffice Calc."
                )
            # try to convert
            metric_name = str(metric_name)
            try:
                metric_value = float(metric_value)
            except ValueError:
                # try to proceed to the next metric
                row_iter = increment_row(row_iter)
                print(
                    f"Could not convert '{metric_value}' into float, proceeding to the next row '{row_iter}'"
                    f" in column '{col_iter}'"
                )
                continue
            # collect
            metric_names.append(metric_name)
            metric_values.append(metric_value)
            # print(f"Checking metric ID {metric_names[-1]}, val {metric_values[-1]}")
            # try to proceed to the next metric
            row_iter = increment_row(row_iter)

        # finished collecting metrics for a given planner
        metrics = dict(zip(metric_names, metric_values))

        # update the planner data with the new set of metrics
        if not planner_name in data.keys():
            # initialize key in dict
            data[planner_name] = {}
            for metric_id, metric_value in metrics.items():
                # assert that values are stored as lists
                data[planner_name][metric_id] = [metric_value]
        else:
            # ready to append new values to an existing lists
            for metric_id in data[planner_name].keys():
                data[planner_name][metric_id].append(metrics[metric_id])

            # make sure that the same metrics are included in each new set of metrics
            num_entries = None
            for metric_id in data[planner_name].keys():
                prev_num_entries = num_entries
                num_entries = len(data[planner_name][metric_id])
                if prev_num_entries == None:
                    continue
                if num_entries != prev_num_entries:
                    raise Exception(
                        f"Number of value entries for metric '{metric_id}' is different than for the previous "
                        f"one ({num_entries} vs {prev_num_entries})"
                    )

        # try to proceed to the next planner
        col_iter = increment_column(col_iter)
        # reset metrics row 'pointer'
        row_iter = increment_row(row_init)

    return data


def load_data_from_excel(path: Path) -> Dict[str, Dict[str, float]]:
    """
    Reads the filtered data from the spreadsheet following the convention introduced in
    `create_excel_from_results.calculate_sheet` function
    """

    # NOTE: data_only allows to read values instead of formulas
    wb = load_workbook(filename = str(path), data_only=True)
    return read_data_from_excel(wb, SHEET_NAME, RESULT_INIT_COL, RESULT_INIT_ROW)


def load_raw_data_from_excel(path: Path) -> Dict[str, Dict[str, List[float]]]:
    """
    Reads the raw data from the spreadsheet following the convention introduced in
    `create_excel_from_results.calculate_sheet` function
    """
    # NOTE: data_only allows to read values instead of formulas
    wb = load_workbook(filename = str(path), data_only=True)
    return read_data_from_excel(wb, SHEET_NAME, RESULT_RAW_INIT_COL, RESULT_RAW_INIT_ROW)
